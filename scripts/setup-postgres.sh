#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=/dev/null
source "${ROOT_DIR}/.env"

systemctl start postgresql

sudo -u postgres psql -v ON_ERROR_STOP=1 <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${CODELEARN_DB_USER}') THEN
    CREATE ROLE ${CODELEARN_DB_USER} LOGIN PASSWORD '${CODELEARN_DB_PASS}';
  ELSE
    ALTER ROLE ${CODELEARN_DB_USER} PASSWORD '${CODELEARN_DB_PASS}';
  END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${JUDGE0_DB_USER}') THEN
    CREATE ROLE ${JUDGE0_DB_USER} LOGIN PASSWORD '${JUDGE0_DB_PASS}';
  ELSE
    ALTER ROLE ${JUDGE0_DB_USER} PASSWORD '${JUDGE0_DB_PASS}';
  END IF;
END\$\$;

SELECT 'CREATE DATABASE ${CODELEARN_DB_NAME} OWNER ${CODELEARN_DB_USER} ENCODING ''UTF8'' LC_COLLATE=''C.UTF-8'' LC_CTYPE=''C.UTF-8'' TEMPLATE template0'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '${CODELEARN_DB_NAME}')\gexec

SELECT 'CREATE DATABASE ${JUDGE0_DB_NAME} OWNER ${JUDGE0_DB_USER} ENCODING ''UTF8'' LC_COLLATE=''C.UTF-8'' LC_CTYPE=''C.UTF-8'' TEMPLATE template0'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '${JUDGE0_DB_NAME}')\gexec

GRANT ALL PRIVILEGES ON DATABASE ${CODELEARN_DB_NAME} TO ${CODELEARN_DB_USER};
GRANT ALL PRIVILEGES ON DATABASE ${JUDGE0_DB_NAME} TO ${JUDGE0_DB_USER};
SQL

echo "PostgreSQL databases ready: ${CODELEARN_DB_NAME}, ${JUDGE0_DB_NAME}"
